"""Generate both frontend contracts from the API models; do not hand-edit them."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import json
import yaml
from app.main import create_app


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    for union in ('anyOf','oneOf'):
        if union in schema:
            return ' | '.join(ts_type(s) for s in schema[union])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v,ensure_ascii=False) for v in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'],ensure_ascii=False)
    kind=schema.get('type')
    if kind=='array':
        return 'Array<'+ts_type(schema['items'])+'>'
    if kind=='object' or 'properties' in schema:
        if 'properties' in schema:
            if not schema['properties']:
                return 'Record<string, never>'
            required=schema.get('required',[])
            props=[f'  {json.dumps(k)}'+('' if k in required else '?')+': '+ts_type(v)+';' for k,v in schema['properties'].items()]
            return '{\n'+'\n'.join(props)+'\n}'
        additional=schema.get('additionalProperties',True)
        return 'Record<string, '+(ts_type(additional) if isinstance(additional,dict) else 'unknown')+'>'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'unknown')


def main():
    root=Path(__file__).resolve().parents[1]
    schema=create_app().openapi()
    (root/'openapi.yaml').write_text(yaml.safe_dump(schema,allow_unicode=True,sort_keys=False),encoding='utf-8')
    header='// Generated by scripts/export_contracts.py; reconstructed team contract v1.\n'
    definitions=['export type '+name+' = '+ts_type(value)+';' for name,value in schema['components']['schemas'].items()]
    (root/'frontend-contract.ts').write_text(header+'\n\n'.join(definitions)+'\n',encoding='utf-8')
    print('Generated openapi.yaml and frontend-contract.ts')


if __name__=='__main__':
    main()
